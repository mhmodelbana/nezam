create or replace function public.student_update_profile(p_updates jsonb)
returns public.students
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_student_id bigint;
  v_student public.students;
  v_name text;
  v_phone text;
  v_pickup text;
  v_university text;
  v_faculty text;
  v_study_year text;
  v_emergency_phone text;
  v_photo text;
begin
  select student_id into v_student_id
  from public.profiles
  where user_id = auth.uid() and role = 'student';
  if v_student_id is null then
    raise exception 'يجب تسجيل الدخول بحساب الطالب لتعديل البيانات.';
  end if;
  if p_updates is null or jsonb_typeof(p_updates) <> 'object' or exists (
    select 1 from jsonb_object_keys(p_updates) as keys(key)
    where key not in (
      'name', 'phone', 'pickup', 'university', 'faculty', 'studyYear',
      'emergencyPhone', 'photoDataUrl'
    )
  ) then
    raise exception 'حقول تعديل الملف الشخصي غير صالحة.';
  end if;

  select * into v_student from public.students where id = v_student_id;
  if not found or v_student.archived_at is not null then
    raise exception 'ملف الطالب غير متاح للتعديل.';
  end if;

  v_name := case when p_updates ? 'name' then btrim(p_updates->>'name') else v_student.name end;
  v_phone := case when p_updates ? 'phone' then btrim(p_updates->>'phone') else v_student.phone end;
  v_pickup := case when p_updates ? 'pickup' then btrim(p_updates->>'pickup') else v_student.pickup end;
  v_university := case when p_updates ? 'university' then btrim(p_updates->>'university') else v_student.university end;
  v_faculty := case when p_updates ? 'faculty' then btrim(p_updates->>'faculty') else v_student.faculty end;
  v_study_year := case when p_updates ? 'studyYear' then btrim(p_updates->>'studyYear') else v_student.study_year end;
  v_emergency_phone := case when p_updates ? 'emergencyPhone' then btrim(p_updates->>'emergencyPhone') else v_student.emergency_phone end;
  v_photo := case when p_updates ? 'photoDataUrl' then p_updates->>'photoDataUrl' else v_student.photo_data_url end;

  if v_name is null or v_name = '' or length(v_name) > 100 then
    raise exception 'اكتب الاسم بالكامل في حدود 100 حرف.';
  end if;
  if v_phone !~ '^\+?[\d\s()-]{7,20}$' then
    raise exception 'تأكد من كتابة رقم هاتف صحيح.';
  end if;
  if v_pickup is null or v_pickup = '' or length(v_pickup) > 160 then
    raise exception 'اكتب منطقة الركوب في حدود 160 حرفًا.';
  end if;
  if length(v_university) > 100 or length(v_faculty) > 100 or
    length(v_study_year) > 100 or length(v_emergency_phone) > 20 then
    raise exception 'تجاوز أحد الحقول الحد المسموح به.';
  end if;
  if v_emergency_phone <> '' and v_emergency_phone !~ '^\+?[\d\s()-]{7,20}$' then
    raise exception 'تأكد من كتابة رقم هاتف ولي الأمر بشكل صحيح.';
  end if;
  if length(v_photo) > 7340032 or
    (v_photo <> '' and v_photo !~ '^data:image/(jpeg|png|webp|gif);base64,[A-Za-z0-9+/]+=*$') then
    raise exception 'صورة الطالب غير صالحة أو أكبر من الحد المسموح.';
  end if;
  if exists (
    select 1 from public.students
    where id <> v_student_id and phone = v_phone
  ) then
    raise exception 'رقم الهاتف مسجل لطالب آخر بالفعل.';
  end if;

  update public.students set
    name = v_name,
    phone = v_phone,
    pickup = v_pickup,
    university = v_university,
    faculty = v_faculty,
    study_year = v_study_year,
    emergency_phone = v_emergency_phone,
    photo_data_url = v_photo,
    updated_at = now()
  where id = v_student_id
  returning * into v_student;
  return v_student;
end;
$$;


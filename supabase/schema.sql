drop function if exists public.student_trip_action(text, bigint, date, bigint);
create function public.student_trip_action(
  p_action text,
  p_schedule_id bigint default null,
  p_trip_date date default null,
  p_request_id bigint default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_student public.students;
  v_schedule public.trip_schedules;
  v_start date;
  v_end date;
begin
  select s.* into v_student
  from public.students s
  join public.profiles p on p.student_id = s.id
  where p.user_id = auth.uid() and p.role = 'student';
  if not found or v_student.archived_at is not null then
    raise exception 'ملف الطالب غير متاح.';
  end if;

  if p_action = 'cancel' then
    update public.trip_requests
    set status = 'cancelled', updated_at = now()
    where id = p_request_id
      and student_id = v_student.id
      and status in ('pending', 'approved');
    if not found then
      raise exception 'لم يتم العثور على حجز نشط.';
    end if;
    return;
  end if;

  if p_action <> 'book' then
    raise exception 'إجراء الحجز غير صالح.';
  end if;
  if p_trip_date is null or p_trip_date <> (now() at time zone 'Africa/Cairo')::date then
    raise exception 'الحجز متاح لرحلات اليوم فقط.';
  end if;
  select * into v_schedule
  from public.trip_schedules
  where id = p_schedule_id and active;
  if not found then
    raise exception 'موعد الرحلة غير متاح.';
  end if;
  if exists (
    select 1 from public.trip_requests
    where student_id = v_student.id
      and trip_date = p_trip_date
      and trip_type = v_schedule.direction
      and status in ('pending', 'approved')
  ) then
    raise exception 'لديك حجز بالفعل لهذا الاتجاه اليوم.';
  end if;
  if v_student.subscription <> 'active' or v_student.term_id is null then
    raise exception 'يلزم وجود اشتراك نشط.';
  end if;

  select coalesce(subscription.start_date, term.start_date),
    coalesce(subscription.end_date, term.end_date)
  into v_start, v_end
  from public.terms term
  left join public.subscriptions subscription
    on subscription.student_id = v_student.id and subscription.term_id = term.id
  where term.id = v_student.term_id;
  if v_start is null or v_end is null then
    raise exception 'تواريخ الاشتراك غير متاحة.';
  end if;
  if p_trip_date < v_start or p_trip_date > v_end then
    raise exception 'الاشتراك غير سارٍ في هذا التاريخ.';
  end if;

  insert into public.trip_requests (
    student_id, student_name, trip_type, trip_date, trip_time, schedule_id,
    destination, pickup, notes, status
  ) values (
    v_student.id, v_student.name, v_schedule.direction, p_trip_date, v_schedule.time,
    v_schedule.id, v_student.pickup, v_student.pickup, '', 'approved'
  );
end;
$$;

create or replace function public.add_subscription_payment(
  p_subscription_id bigint,
  p_payment jsonb
)
returns public.subscriptions
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_subscription public.subscriptions;
  v_payment jsonb;
begin
  if not public.is_vota_admin() then
    raise exception 'يجب تسجيل الدخول بحساب الإدارة لإضافة دفعة.';
  end if;
  if p_payment is null or jsonb_typeof(p_payment) <> 'object' then
    raise exception 'بيانات الدفعة غير صالحة.';
  end if;

  select * into v_subscription
  from public.subscriptions
  where id = p_subscription_id
  for update;
  if not found then
    raise exception 'الاشتراك غير موجود.';
  end if;

  v_payment := p_payment;
  if not (v_payment ? 'id') then
    v_payment := v_payment || jsonb_build_object('id', 'payment-' || p_subscription_id || '-' || extract(epoch from clock_timestamp()));
  end if;
  if not (v_payment ? 'receiptNumber') then
    v_payment := v_payment || jsonb_build_object('receiptNumber', 'VOTA-' || p_subscription_id || '-' || extract(epoch from clock_timestamp()));
  end if;

  update public.subscriptions set
    payments = payments || jsonb_build_array(v_payment),
    payment_audit = payment_audit || jsonb_build_array(jsonb_build_object(
      'id', clock_timestamp()::text,
      'changedAt', clock_timestamp(),
      'action', 'payment-added',
      'paymentId', coalesce(v_payment->>'receiptNumber', v_payment->>'id'),
      'before', null,
      'after', v_payment
    )),
    updated_at = now()
  where id = p_subscription_id
  returning * into v_subscription;
  return v_subscription;
end;
$$;

create or replace function public.import_local_state(p_state jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_table text;
  v_sequence text;
  v_max_id bigint;
  v_settings jsonb;
begin
  if not public.is_vota_admin() then
    raise exception 'يجب تسجيل الدخول بحساب الإدارة لاستيراد البيانات.';
  end if;
  if p_state is null or jsonb_typeof(p_state) <> 'object' then
    raise exception 'ملف البيانات المحلية غير صالح.';
  end if;
  if exists (select 1 from public.students) or
     exists (select 1 from public.terms) or
     exists (select 1 from public.subscriptions) or
     exists (select 1 from public.trip_schedules) or
     exists (select 1 from public.trip_requests) then
    raise exception 'قاعدة البيانات تحتوي سجلات بالفعل؛ أوقف الاستيراد لتجنب تكرارها.';
  end if;

  insert into public.terms (id, name, academic_year, start_date, end_date, created_at, updated_at)
  select id, name, "academicYear", coalesce("priceCents", 1),
    nullif("startDate", '')::date, nullif("endDate", '')::date,
    coalesce(nullif("createdAt", '')::timestamptz, now()),
    coalesce(nullif("updatedAt", '')::timestamptz, now())
  from jsonb_to_recordset(coalesce(p_state->'terms', '[]'::jsonb)) as term_rows(
    id bigint, name text, "academicYear" text, "priceCents" bigint,
    "startDate" text, "endDate" text,
    "createdAt" text, "updatedAt" text
  );

  insert into public.students (
    id, name, phone, pickup, university, faculty, study_year, emergency_phone,
    subscription, term_id, notes, archived_at, must_change_password,
    photo_data_url, created_at, updated_at
  )
  select id, name, phone, pickup, coalesce(university, ''), coalesce(faculty, ''),
    coalesce("studyYear", ''), coalesce("emergencyPhone", ''), coalesce(subscription, 'active'),
    "termId", coalesce(notes, ''), nullif("archivedAt", '')::timestamptz,
    coalesce("mustChangePassword", true), coalesce("photoDataUrl", ''),
    coalesce(nullif("createdAt", '')::timestamptz, now()),
    coalesce(nullif("updatedAt", '')::timestamptz, now())
  from jsonb_to_recordset(coalesce(p_state->'students', '[]'::jsonb)) as student_rows(
    id bigint, name text, phone text, pickup text, university text, faculty text,
    "studyYear" text, "emergencyPhone" text, subscription text, "termId" bigint,
    notes text, "archivedAt" text, "mustChangePassword" boolean, "photoDataUrl" text,
    "createdAt" text, "updatedAt" text
  );

  insert into public.subscriptions (
    id, student_id, term_id, price_cents, start_date, end_date, payments,
    payment_audit, created_at, updated_at
  )
  select id, "studentId", "termId", coalesce("priceCents", 0),
    nullif("startDate", '')::date, nullif("endDate", '')::date,
    coalesce(payments, '[]'::jsonb), coalesce("paymentAudit", '[]'::jsonb),
    coalesce(nullif("createdAt", '')::timestamptz, now()),
    coalesce(nullif("updatedAt", '')::timestamptz, now())
  from jsonb_to_recordset(coalesce(p_state->'subscriptions', '[]'::jsonb)) as subscription_rows(
    id bigint, "studentId" bigint, "termId" bigint, "priceCents" bigint,
    "startDate" text, "endDate" text, payments jsonb, "paymentAudit" jsonb,
    "createdAt" text, "updatedAt" text
  );

  insert into public.trip_schedules (id, direction, time, active, created_at, updated_at)
  select id, direction, time, coalesce(active, true),
    coalesce(nullif("createdAt", '')::timestamptz, now()),
    coalesce(nullif("updatedAt", '')::timestamptz, now())
  from jsonb_to_recordset(coalesce(p_state->'tripSchedules', '[]'::jsonb)) as schedule_rows(
    id bigint, direction text, time text, active boolean, "createdAt" text, "updatedAt" text
  );

  insert into public.trip_requests (
    id, student_id, student_name, trip_type, trip_date, trip_time, schedule_id,
    destination, pickup, notes, status, created_at, updated_at
  )
  select id, "studentId", coalesce("studentName", ''), "tripType", "tripDate"::date,
    "tripTime", "scheduleId", coalesce(destination, ''), coalesce(pickup, ''),
    coalesce(notes, ''), coalesce(status, 'pending'),
    coalesce(nullif("createdAt", '')::timestamptz, now()),
    coalesce(nullif("updatedAt", '')::timestamptz, now())
  from jsonb_to_recordset(coalesce(p_state->'tripRequests', '[]'::jsonb)) as request_rows(
    id bigint, "studentId" bigint, "studentName" text, "tripType" text, "tripDate" text,
    "tripTime" text, "scheduleId" bigint, destination text, pickup text, notes text,
    status text, "createdAt" text, "updatedAt" text
  );

  v_settings := coalesce(p_state->'systemSettings', '{}'::jsonb);
  update public.system_settings set
    company_name = coalesce(nullif(v_settings->>'companyName', ''), company_name),
    company_phone = coalesce(v_settings->>'companyPhone', company_phone),
    company_address = coalesce(v_settings->>'companyAddress', company_address),
    logo_data_url = coalesce(v_settings->>'logoDataUrl', logo_data_url),
    primary_color = coalesce(v_settings->>'primaryColor', primary_color),
    trip_labels = coalesce(v_settings->'tripLabels', trip_labels),
    pickup_areas = coalesce(v_settings->'pickupAreas', pickup_areas),
    updated_at = now()
  where id = 1;

  foreach v_table in array array['terms', 'students', 'subscriptions', 'trip_schedules', 'trip_requests']
  loop
    v_sequence := pg_get_serial_sequence(format('public.%I', v_table), 'id');
    execute format('select max(id) from public.%I', v_table) into v_max_id;
    if v_sequence is not null and v_max_id is not null then
      perform setval(v_sequence, v_max_id, true);
    end if;
  end loop;

  return jsonb_build_object(
